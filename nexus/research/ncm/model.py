"""Research-only Neural Causal Model (NCM) prototype.

This implementation is intentionally isolated from live order generation. A
user-specified DAG and point-in-time features are required; it does not discover
causal structure automatically or establish causal identifiability.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Mapping, Sequence

import numpy as np
import pandas as pd
from sklearn.neural_network import MLPRegressor


@dataclass(frozen=True)
class _Mechanism:
    model: MLPRegressor
    x_mean: np.ndarray
    x_scale: np.ndarray
    y_mean: float
    y_scale: float
    residuals: np.ndarray


class NeuralCausalModel:
    """A declared-DAG SCM with neural conditional mechanisms.

    The graph maps each node to its ordered parent names, for example:
    {"asset_return_lag1": (), "volatility_lag1": (),
     "next_return": ("asset_return_lag1", "volatility_lag1")}.

    Root nodes are sampled from the empirical training distribution. Non-root
    nodes are generated by a fitted MLP mechanism plus bootstrapped in-sample
    residuals. This is a research approximation, not a production financial model.
    """

    def __init__(
        self,
        graph: Mapping[str, Sequence[str]],
        hidden_layer_sizes: tuple[int, ...] = (32, 16),
        max_iter: int = 400,
        random_state: int = 42,
    ) -> None:
        if not graph:
            raise ValueError("The causal graph must contain at least one node.")
        self.graph: dict[str, tuple[str, ...]] = {}
        for raw_node, raw_parents in graph.items():
            if not isinstance(raw_node, str) or not raw_node.strip():
                raise ValueError("Graph node names must be non-empty strings.")
            node = raw_node.strip()
            parents = tuple(raw_parents)
            if any(not isinstance(parent, str) or not parent.strip() for parent in parents):
                raise ValueError(f"Parents of {node!r} must be non-empty names.")
            parents = tuple(parent.strip() for parent in parents)
            if node in parents:
                raise ValueError(f"Node {node!r} cannot be its own parent.")
            if len(set(parents)) != len(parents):
                raise ValueError(f"Parents of {node!r} must be unique.")
            self.graph[node] = parents

        unknown = {
            parent for parents in self.graph.values() for parent in parents
            if parent not in self.graph
        }
        if unknown:
            raise ValueError(f"Graph references unknown parents: {sorted(unknown)}")
        if any(not isinstance(size, int) or size < 1 for size in hidden_layer_sizes):
            raise ValueError("Hidden layer sizes must be positive integers.")
        if max_iter < 1:
            raise ValueError("max_iter must be positive.")

        self.order = self._topological_order()
        self.hidden_layer_sizes = hidden_layer_sizes
        self.max_iter = int(max_iter)
        self.random_state = int(random_state)
        self._root_samples: dict[str, np.ndarray] = {}
        self._mechanisms: dict[str, _Mechanism] = {}
        self.training_rows = 0
        self.is_fitted = False

    def _topological_order(self) -> tuple[str, ...]:
        """Return a stable topological ordering or reject a cyclic graph."""
        order: list[str] = []
        remaining = list(self.graph)
        while remaining:
            ready = [
                node for node in remaining
                if all(parent in order for parent in self.graph[node])
            ]
            if not ready:
                raise ValueError("The causal graph contains a directed cycle.")
            for node in ready:
                order.append(node)
                remaining.remove(node)
        return tuple(order)

    def fit(self, data: pd.DataFrame) -> "NeuralCausalModel":
        """Fit mechanisms on a training slice only; no temporal split is inferred."""
        if not isinstance(data, pd.DataFrame):
            raise TypeError("data must be a pandas DataFrame.")
        if len(data) < 50:
            raise ValueError("At least 50 training rows are required for research fitting.")
        missing = [node for node in self.graph if node not in data.columns]
        if missing:
            raise ValueError(f"Training data is missing graph nodes: {missing}")

        try:
            frame = data.loc[:, list(self.graph)].apply(pd.to_numeric, errors="coerce")
            values = frame.to_numpy(dtype=np.float64)
        except (TypeError, ValueError) as exc:
            raise ValueError("All causal-model columns must be numeric.") from exc
        if not np.isfinite(values).all():
            raise ValueError("Training data contains missing or non-finite causal variables.")

        roots: dict[str, np.ndarray] = {}
        mechanisms: dict[str, _Mechanism] = {}
        for index, node in enumerate(self.order):
            parents = self.graph[node]
            target = frame[node].to_numpy(dtype=np.float64)
            if not parents:
                roots[node] = target.copy()
                continue

            x = frame.loc[:, list(parents)].to_numpy(dtype=np.float64)
            x_mean = x.mean(axis=0)
            x_scale = x.std(axis=0)
            x_scale[x_scale < 1e-12] = 1.0
            y_mean = float(target.mean())
            y_scale = float(target.std())
            if y_scale < 1e-12:
                y_scale = 1.0

            model = MLPRegressor(
                hidden_layer_sizes=self.hidden_layer_sizes,
                activation="tanh",
                solver="adam",
                alpha=1e-3,
                batch_size=min(64, len(frame)),
                learning_rate_init=1e-3,
                max_iter=self.max_iter,
                random_state=self.random_state + index,
                shuffle=True,
                early_stopping=False,
                n_iter_no_change=25,
            )
            model.fit((x - x_mean) / x_scale, (target - y_mean) / y_scale)
            fitted = model.predict((x - x_mean) / x_scale) * y_scale + y_mean
            residuals = target - fitted
            mechanisms[node] = _Mechanism(
                model=model,
                x_mean=x_mean,
                x_scale=x_scale,
                y_mean=y_mean,
                y_scale=y_scale,
                residuals=residuals.astype(np.float64, copy=True),
            )

        self._root_samples = roots
        self._mechanisms = mechanisms
        self.training_rows = len(frame)
        self.is_fitted = True
        return self

    def predict_target(self, observations: pd.DataFrame, target: str) -> np.ndarray:
        """Predict a non-root target conditional on its declared parent columns."""
        self._require_fitted()
        if target not in self.graph:
            raise ValueError(f"Unknown target node: {target!r}")
        if not self.graph[target]:
            raise ValueError(f"Root node {target!r} has no conditional mechanism.")
        missing = [parent for parent in self.graph[target] if parent not in observations]
        if missing:
            raise ValueError(f"Prediction rows are missing parent columns: {missing}")

        x = observations.loc[:, list(self.graph[target])].apply(
            pd.to_numeric, errors="coerce"
        ).to_numpy(dtype=np.float64)
        if not np.isfinite(x).all():
            raise ValueError("Prediction parents contain missing or non-finite values.")
        mechanism = self._mechanisms[target]
        scaled = (x - mechanism.x_mean) / mechanism.x_scale
        prediction = mechanism.model.predict(scaled) * mechanism.y_scale + mechanism.y_mean
        if not np.isfinite(prediction).all():
            raise ValueError("NCM produced non-finite predictions.")
        return np.asarray(prediction, dtype=np.float64)

    def simulate(
        self,
        n_samples: int = 1000,
        interventions: Mapping[str, float | Sequence[float] | np.ndarray] | None = None,
        random_state: int | None = None,
    ) -> pd.DataFrame:
        """Sample the SCM under optional do-interventions using residual bootstrap."""
        self._require_fitted()
        if not isinstance(n_samples, int) or n_samples < 1:
            raise ValueError("n_samples must be a positive integer.")
        intervention_values = dict(interventions or {})
        unknown = set(intervention_values) - set(self.graph)
        if unknown:
            raise ValueError(f"Interventions target unknown nodes: {sorted(unknown)}")

        rng = np.random.default_rng(
            self.random_state if random_state is None else random_state
        )
        generated: dict[str, np.ndarray] = {}
        for node in self.order:
            if node in intervention_values:
                raw = np.asarray(intervention_values[node], dtype=np.float64)
                if raw.ndim == 0:
                    values = np.full(n_samples, float(raw), dtype=np.float64)
                elif raw.ndim == 1 and len(raw) == n_samples:
                    values = raw.astype(np.float64, copy=True)
                else:
                    raise ValueError(
                        f"Intervention for {node!r} must be scalar or length {n_samples}."
                    )
                if not np.isfinite(values).all():
                    raise ValueError(f"Intervention for {node!r} is non-finite.")
                generated[node] = values
                continue

            parents = self.graph[node]
            if not parents:
                generated[node] = rng.choice(
                    self._root_samples[node], size=n_samples, replace=True
                )
                continue

            mechanism = self._mechanisms[node]
            x = np.column_stack([generated[parent] for parent in parents])
            scaled = (x - mechanism.x_mean) / mechanism.x_scale
            conditional_mean = (
                mechanism.model.predict(scaled) * mechanism.y_scale + mechanism.y_mean
            )
            noise = rng.choice(mechanism.residuals, size=n_samples, replace=True)
            generated[node] = conditional_mean + noise

        result = pd.DataFrame(generated, columns=list(self.order))
        if not np.isfinite(result.to_numpy(dtype=np.float64)).all():
            raise ValueError("SCM simulation produced non-finite values.")
        return result

    def metadata(self) -> dict[str, Any]:
        """Return concise metadata suitable for experiment manifests."""
        return {
            "model_type": "NeuralCausalModel",
            "graph": {node: list(parents) for node, parents in self.graph.items()},
            "topological_order": list(self.order),
            "hidden_layer_sizes": list(self.hidden_layer_sizes),
            "max_iter": self.max_iter,
            "random_state": self.random_state,
            "training_rows": self.training_rows,
            "fitted": self.is_fitted,
            "research_only": True,
        }

    def _require_fitted(self) -> None:
        if not self.is_fitted:
            raise RuntimeError("NCM must be fitted on a training slice before inference.")
